"""Synchronize recoil core, validation fixtures and tooling between selected source repos."""
import argparse
import re
from pathlib import Path


def recoil_headers(client):
    """The shared recoil core: every header under src/recoil, mirrored to the server unchanged."""
    root = client / 'src/recoil'
    return sorted(path.relative_to(root) for path in root.rglob('*.h'))


# The contract constants the Python validators use; engine and simulation constants stay in C.
EXPORTS = ('WIRE_VERSION', 'WIRE_SIZE', 'MAX_WEAPONS', 'WEAPON_NAME')


def python_constants(client):
    """The Python tooling's contract: limits, the model registry and each model's parameter bounds."""
    root = client / 'src/recoil'
    text = '\n'.join((root / header).read_text(encoding='utf-8') for header in recoil_headers(client))
    enum = {}
    for body in re.findall(r'enum \{(.*?)\};', text, re.S):
        enum.update((name, int(value)) for name, value in re.findall(r'(RECOIL_[A-Z0-9_]+) = (-?\d+)', body))
    value = lambda token: int(token) if token.isdigit() else enum[token]
    native = re.search(r'#define RECOIL_NATIVE_WIRE "([^"]+)"', text).group(1)
    names, params = [], []
    # Registry entries: {ID, "name", params table, its count, ...}; the count is derived in C (sizeof).
    for ident, name, table in re.findall(r'\{(RECOIL_[A-Z0-9_]+), "([a-z0-9_-]+)", (\w+), [^,]+,', text):
        bounds = () if table == 'NULL' else tuple(
            (param, value(low), value(high)) for param, low, high in
            re.findall(r'\{"(\w+)", (\w+), (\w+)\}', re.search(table + r'\[\] = \{(.*?)\};', text, re.S).group(1)))
        names.append(f"{enum[ident]}: '{name}'")
        params.append(f'{enum[ident]}: {bounds!r}')
    lines = ['"""GENERATED by CoD4x_Client_pub/tools/sync-recoil.py from src/recoil/*.h; do not edit."""']
    lines += [f'{name} = {enum["RECOIL_" + name]}' for name in EXPORTS]
    lines += [f"NATIVE_WIRE = '{native}'", f'MODELS = {{{", ".join(names)}}}',
              '# Per-weapon parameters of each model: (name, min, max).', f'MODEL_PARAMS = {{{", ".join(params)}}}', '']
    return '\n'.join(lines).encode('ascii')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--server', type=Path)
    parser.add_argument('--mod', type=Path)
    parser.add_argument('--release', type=Path)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    client = Path(__file__).resolve().parents[1]
    explicit = any((args.server, args.mod, args.release))
    server = args.server or (client.parent / 'CoD4x_Server' if not explicit else None)
    mod = args.mod or (client.parent / 'promod-econ-na' if not explicit else None)
    release = args.release or (client.parent / 'cod4-promod' if not explicit else None)
    corpus = client / 'tests/fixtures/recoil-contracts.tsv'
    constants = python_constants(client)
    pairs, generated = [], []
    if server and server.is_dir():
        pairs += [(client / 'src/recoil' / header, server / 'src/recoil' / header) for header in recoil_headers(client)]
        pairs += [(corpus, server / 'tools/tests/recoil-contracts.tsv')]
    if mod and mod.is_dir():
        pairs += [(corpus, mod / 'tools/tests/recoil-contracts.tsv')]
        generated.append(mod / 'tools/recoil_constants.py')
    if release and release.is_dir():
        module = (mod or client.parent / 'promod-econ-na') / 'tools/recoil_contract.py'
        pairs += [(module, release / 'scripts/recoil_contract.py'),
                  (corpus, release / 'scripts/fixtures/recoil-contracts.tsv')]
        generated.append(release / 'scripts/recoil_constants.py')
    if not pairs:
        raise SystemExit('Pass a source repository path with --server, --mod or --release.')
    for target, data in [(target, source.read_bytes()) for source, target in pairs] + [(t, constants) for t in generated]:
        if args.check:
            if not target.is_file() or target.read_bytes() != data:
                raise SystemExit(f'Recoil mirror differs: {target}; run tools/sync-recoil.py.')
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(data)
    print(f'Recoil mirrors {"verified" if args.check else "updated"}: {len(pairs) + len(generated)} files.')


if __name__ == '__main__':
    main()
